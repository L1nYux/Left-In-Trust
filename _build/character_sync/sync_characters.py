def main():
    report=[]
    for f in sorted(OUT.glob('*.docx')):
        # Never overwrite the first pre-edit copy on a subsequent QA iteration.
        if not (BACKUP/f.name).exists(): shutil.copy2(f,BACKUP/f.name)
        md=ROOT/'_build/src'/(f.stem+'.md')
        if md.exists() and not (BACKUP/md.name).exists(): shutil.copy2(md,BACKUP/md.name)
        d=Document(BACKUP/f.name)
        count=len(CHANGES)
        if f.stem=='00_索引': patch_index(d)
        else: patch_character(d,f.stem)
        polish(d)
        d.save(f)
        md.write_text(export_md(d),encoding='utf-8')
        report.append({'file':f.name,'changes':len(CHANGES)-count})
        print('Updated',f.name)
    (QA/'change_log.json').write_text(json.dumps({'files':report,'replacements':CHANGES},ensure_ascii=False,indent=2),encoding='utf-8')

if __name__=='__main__': main()
